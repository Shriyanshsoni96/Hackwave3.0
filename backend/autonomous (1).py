import pandas as pd
from sklearn.compose import ColumnTransformer
from sklearn.preprocessing import OneHotEncoder
from sklearn.pipeline import Pipeline
from sklearn.impute import SimpleImputer
from sklearn.ensemble import RandomForestClassifier
from sklearn.metrics import (
    classification_report,
    confusion_matrix,
    average_precision_score,
    roc_auc_score
)

# December 2025 exclude: no positive labels in that month
data = df[df["month"] < "2025-12-01"].copy()

# Chronological split: older months for training, newer months for testing
train = data[data["month"] < "2025-09-01"].copy()
test = data[data["month"] >= "2025-09-01"].copy()

target = "churned_next_month"
drop_cols = ["user_id", "month", "churned", target]

X_train = train.drop(columns=drop_cols)
y_train = train[target]

X_test = test.drop(columns=drop_cols)
y_test = test[target]

print("Train shape:", X_train.shape)
print("Test shape:", X_test.shape)
print("\nTrain target counts:\n", y_train.value_counts())
print("\nTest target counts:\n", y_test.value_counts())

# Preprocessing
categorical = X_train.select_dtypes(
    include=["object", "category"]
).columns.tolist()

numeric = X_train.select_dtypes(
    include=["number"]
).columns.tolist()

preprocessor = ColumnTransformer([
    ("num", SimpleImputer(strategy="median"), numeric),
    ("cat", Pipeline([
        ("imputer", SimpleImputer(strategy="most_frequent")),
        ("encoder", OneHotEncoder(handle_unknown="ignore"))
    ]), categorical)
])

model = Pipeline([
    ("prep", preprocessor),
    ("rf", RandomForestClassifier(
        n_estimators=200,
        class_weight="balanced",
        random_state=42,
        n_jobs=-1
    ))
])

model.fit(X_train, y_train)

pred = model.predict(X_test)
prob = model.predict_proba(X_test)[:, 1]

print("\nClassification report:")
print(classification_report(y_test, pred, zero_division=0))

print("Confusion matrix:\n", confusion_matrix(y_test, pred))
print("PR-AUC / Average precision:", round(
    average_precision_score(y_test, prob), 4
))

if y_test.nunique() == 2:
    print("ROC-AUC:", round(roc_auc_score(y_test, prob), 4))

